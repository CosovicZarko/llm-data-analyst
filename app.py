"""Original Streamlit layout, using the locally installed fine-tuned SQL model."""
from __future__ import annotations

import time
from pathlib import Path

import streamlit as st

from app_workflow import execute_for_model, generate_for_model
from dataset_utils import load_file
from example_questions import MAX_BATCH_QUESTIONS, prepare_questions, suggested_questions

ROOT = Path(__file__).parent
# The weights are in Ollama (~/.ollama/models), NOT in this Python project.
# Use the same raw inference path for SQL generation and a single bounded repair.
MODEL = "qwen-sql-analyst:v1"

st.set_page_config(page_title="LLM Data Analyst", layout="wide")
st.title("LLM Data Analyst")
st.write("Upload a table, ask a question, and inspect the SQL and results generated by a language model.")

example_path = ROOT / "data" / "sample_sales.csv"
mode = st.radio("Dataset", ["Try sample sales data", "Upload CSV or Excel"], horizontal=True)

if mode == "Try sample sales data":
    source_name = example_path.name
    payload = example_path.read_bytes()
else:
    uploaded = st.file_uploader("Choose CSV or Excel file", type=["csv", "xlsx"])
    if uploaded is None:
        st.info("Upload a file to begin.")
        st.stop()
    source_name, payload = uploaded.name, uploaded.getvalue()

try:
    data = load_file(source_name, payload)
except ValueError as exc:
    st.error(str(exc))
    st.stop()

st.caption(f"{len(data.frame):,} rows · {len(data.frame.columns)} columns · SQL table: dataset")
with st.expander("View table and column names", expanded=True):
    st.dataframe(data.frame.head(10), use_container_width=True, hide_index=True)
    if any(label.split(" (column ")[0] != normalized for label, normalized in data.column_map.items()):
        st.caption("Column names were normalized for SQL: " + ", ".join(
            f"{orig.rsplit(' (column ', 1)[0]} → {name}" for orig, name in data.column_map.items()
        ))

examples = suggested_questions(data.frame)
with st.form("ask"):
    selected = st.multiselect(
        "Choose from example questions",
        options=examples,
        default=examples[:1],
        max_selections=MAX_BATCH_QUESTIONS,
        help=f"Choose up to {MAX_BATCH_QUESTIONS} examples. All use columns from your current dataset.",
    )
    question = st.text_area(
        "Or ask your own question (optional)",
        value="",
        placeholder="For example: What is the average order value by region?",
        max_chars=1200,
        height=90,
    )
    submitted = st.form_submit_button("Generate and run SQL", type="primary")

if submitted:
    try:
        questions = prepare_questions(selected, question)
    except ValueError as exc:
        st.warning(str(exc))
    else:
        st.subheader("Results")
        for i, query in enumerate(questions, start=1):
            st.write(f"**Question {i}:** {query}")
            generated = None
            try:
                started = time.perf_counter()
                with st.spinner("Generating SQL with the language model..."):
                    generated = generate_for_model(query, data.schema, MODEL)
                generation_seconds = time.perf_counter() - started
                with st.spinner("Executing SQL (and correcting an error if needed)..."):
                    execution = execute_for_model(
                        data.frame, query, data.schema, generated, MODEL
                    )
                if execution.repaired:
                    st.caption("The first SQL query failed in DuckDB and was corrected using its error message.")
                    with st.expander("See first SQL attempt and database error"):
                        st.code(generated, language="sql")
                        st.text(execution.initial_error or "Unknown database error")
                if len(execution.rows):
                    st.dataframe(execution.rows, use_container_width=True, hide_index=True)
                else:
                    st.info("Query succeeded but returned no rows.")
                st.caption(
                    f"{len(execution.rows)} row(s) returned (maximum 100) · "
                    f"Generation: {generation_seconds:.1f}s"
                )
                st.write("**Generated SQL**")
                st.code(execution.sql, language="sql")
            except Exception as exc:
                # Never display a failed or unsafe query as a successful answer.
                st.error(f"Could not run this query: {exc}")
                if generated is not None:
                    st.caption("Generated SQL (not successfully executed)")
                    st.code(generated, language="sql")
            if i < len(questions):
                st.divider()
